#!/usr/bin/env python3
"""Recreate the nine paper certificates by exact positive time scaling."""
import argparse
import copy
from fractions import Fraction
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def scaled_certificate(cert, scale):
    scale = Fraction(scale)
    if scale <= 0:
        raise ValueError('Time scale must be positive')
    out = copy.deepcopy(cert)
    out.pop('theta_normalized', None)
    for key in ('a', 'b', 'h'):
        out[key] = [str(Fraction(x) * scale) for x in cert[key]]
    out['factor_unit'] = str(Fraction(cert['factor_unit']) * scale)
    out['resultant'] = str(Fraction(cert['resultant']) * scale**4)
    for reaction in out['reactions']:
        reaction['rate'] = str(Fraction(reaction['rate']) * scale)
    return out


def encoded(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='Write regenerated certificates to this directory')
    parser.add_argument('--check', action='store_true', help='Compare regenerated bytes with the shipped certificates')
    args = parser.parse_args()
    if not args.output and not args.check:
        parser.error('Choose --output DIRECTORY or --check')
    index = json.loads((ROOT/'certificates/index.json').read_text())
    for row in index['witnesses']:
        source = json.loads((ROOT/row['source_certificate']).read_text())
        regenerated = encoded(scaled_certificate(source, row['positive_time_scale']))
        target = ROOT/row['certificate']
        if args.check and target.read_bytes() != regenerated:
            raise ValueError(f'Regeneration differs: {row["certificate"]}')
        if args.output:
            args.output.mkdir(parents=True, exist_ok=True)
            (args.output/target.name).write_bytes(regenerated)
    print(json.dumps({'status': 'PASS', 'certificates': len(index['witnesses']),
                      'byte_comparison': bool(args.check)}))


if __name__ == '__main__':
    main()
